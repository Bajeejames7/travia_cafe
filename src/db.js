'use strict';
/**
 * Database layer. Uses PostgreSQL when DATABASE_URL is set (production on Render + Aiven),
 * otherwise a local SQLite file (zero-setup local preview). Both expose the same async API:
 *
 *   await db.all(sql, ...params)   -> rows
 *   await db.get(sql, ...params)   -> first row or undefined
 *   await db.run(sql, ...params)   -> { changes }
 *   await db.tx(async (t) => { await t.get(...); ... })   -> runs inside one transaction
 *
 * SQL uses `?` placeholders and only syntax both databases understand.
 */
const fs = require('fs');
const path = require('path');

const DATA_DIR = path.resolve(process.env.DATA_DIR || path.join(__dirname, '..', 'data'));
const VIDEO_DIR = path.join(DATA_DIR, 'videos');
fs.mkdirSync(VIDEO_DIR, { recursive: true });

const DATABASE_URL = process.env.DATABASE_URL || '';
const IS_PG = /^postgres(ql)?:\/\//i.test(DATABASE_URL);

function schema(pg) {
  const id = pg ? 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : 'INTEGER PRIMARY KEY';
  const big = pg ? 'BIGINT' : 'INTEGER';
  // ISO-8601 UTC timestamps stored as text, identical in both databases so they sort and compare the same.
  const now = pg
    ? `(to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'))`
    : `(strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))`;
  return `
CREATE TABLE IF NOT EXISTS settings (
  key   TEXT PRIMARY KEY,
  value TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS staff (
  id         ${id},
  name       TEXT NOT NULL,
  email      TEXT NOT NULL UNIQUE,     -- always stored lowercase
  pass_hash  TEXT NOT NULL,
  role       TEXT NOT NULL CHECK (role IN ('admin', 'teacher')),
  active     INTEGER NOT NULL DEFAULT 1,
  created_at TEXT NOT NULL DEFAULT ${now}
);

CREATE TABLE IF NOT EXISTS staff_sessions (
  token_hash TEXT PRIMARY KEY,
  staff_id   INTEGER NOT NULL REFERENCES staff(id) ON DELETE CASCADE,
  expires_at ${big} NOT NULL
);

CREATE TABLE IF NOT EXISTS modules (
  id             ${id},
  title          TEXT NOT NULL,
  description    TEXT NOT NULL DEFAULT '',
  sort           INTEGER NOT NULL DEFAULT 0,
  price_self     INTEGER NOT NULL,
  price_live     INTEGER NOT NULL,
  price_physical INTEGER NOT NULL,
  active         INTEGER NOT NULL DEFAULT 1,
  created_at     TEXT NOT NULL DEFAULT ${now}
);

CREATE TABLE IF NOT EXISTS videos (
  id         ${id},
  module_id  INTEGER NOT NULL REFERENCES modules(id) ON DELETE CASCADE,
  title      TEXT NOT NULL,
  filename   TEXT NOT NULL,
  mime       TEXT NOT NULL,
  size       ${big} NOT NULL,
  sort       INTEGER NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL DEFAULT ${now}
);

-- A scheduled live (online) or physical class for a module.
CREATE TABLE IF NOT EXISTS classes (
  id           ${id},
  module_id    INTEGER NOT NULL REFERENCES modules(id),
  mode         TEXT NOT NULL CHECK (mode IN ('live', 'physical')),
  title        TEXT NOT NULL,
  starts_at    TEXT NOT NULL,            -- local Nairobi time, 'YYYY-MM-DDTHH:MM'
  duration_min INTEGER NOT NULL DEFAULT 60,
  location     TEXT NOT NULL DEFAULT '', -- physical classes
  meeting_link TEXT NOT NULL DEFAULT '', -- live classes; never shown publicly
  capacity     INTEGER NOT NULL DEFAULT 0, -- 0 = unlimited
  teacher_id   INTEGER REFERENCES staff(id) ON DELETE SET NULL,
  created_at   TEXT NOT NULL DEFAULT ${now}
);

CREATE TABLE IF NOT EXISTS students (
  id             ${id},
  name           TEXT NOT NULL,
  email          TEXT NOT NULL UNIQUE,   -- always stored lowercase
  phone          TEXT NOT NULL DEFAULT '',
  pass_hash      TEXT,                   -- NULL for Google-only accounts
  google_sub     TEXT UNIQUE,
  email_verified INTEGER NOT NULL DEFAULT 0,
  active         INTEGER NOT NULL DEFAULT 1,
  created_at     TEXT NOT NULL DEFAULT ${now},
  last_login_at  TEXT
);

CREATE TABLE IF NOT EXISTS enrollments (
  id            ${id},
  ref           TEXT NOT NULL UNIQUE,
  name          TEXT NOT NULL,
  email         TEXT NOT NULL,
  phone         TEXT NOT NULL,
  track         TEXT NOT NULL CHECK (track IN ('self', 'live', 'physical')),
  module_id     INTEGER NOT NULL REFERENCES modules(id),
  class_id      INTEGER REFERENCES classes(id) ON DELETE SET NULL,
  student_id    INTEGER REFERENCES students(id) ON DELETE SET NULL,
  amount        INTEGER NOT NULL,
  -- awaiting_payment -> pending_review -> confirmed | rejected
  status        TEXT NOT NULL DEFAULT 'awaiting_payment',
  mpesa_code    TEXT UNIQUE,
  paid_at       TEXT,
  reject_reason TEXT,
  code_hash     TEXT UNIQUE,             -- sha256 of the one-time access code
  code_used_at  TEXT,
  confirmed_at  TEXT,
  confirmed_by  INTEGER REFERENCES staff(id) ON DELETE SET NULL,
  link_sent_at  TEXT,
  created_at    TEXT NOT NULL DEFAULT ${now}
);
CREATE INDEX IF NOT EXISTS enrollments_status ON enrollments(status);
CREATE INDEX IF NOT EXISTS enrollments_class ON enrollments(class_id);
CREATE INDEX IF NOT EXISTS enrollments_student ON enrollments(student_id);

CREATE TABLE IF NOT EXISTS student_sessions (
  token_hash TEXT PRIMARY KEY,
  student_id INTEGER NOT NULL REFERENCES students(id) ON DELETE CASCADE,
  expires_at ${big} NOT NULL,
  created_at ${big} NOT NULL,
  user_agent TEXT NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS password_resets (
  token_hash TEXT PRIMARY KEY,
  student_id INTEGER NOT NULL REFERENCES students(id) ON DELETE CASCADE,
  expires_at ${big} NOT NULL
);

CREATE TABLE IF NOT EXISTS outbox (
  id         ${id},
  to_email   TEXT NOT NULL,
  subject    TEXT NOT NULL,
  body       TEXT NOT NULL,
  status     TEXT NOT NULL,              -- sent | logged | failed
  error      TEXT,
  created_at TEXT NOT NULL DEFAULT ${now}
);
`;
}

// ---------------------------------------------------------------------------
// PostgreSQL
// ---------------------------------------------------------------------------
function createPg() {
  const pg = require('pg');
  // COUNT(*) and BIGINT come back as strings by default; every number we store fits in a JS number.
  pg.types.setTypeParser(20, (v) => Number(v));

  // node-pg lets sslmode in the URL override the ssl option, so strip it and decide here.
  const url = new URL(DATABASE_URL);
  const wantsSsl = url.searchParams.has('sslmode') && url.searchParams.get('sslmode') !== 'disable';
  url.searchParams.delete('sslmode');
  let ssl = false;
  if (process.env.DATABASE_CA_CERT) {
    // Aiven: paste the project's CA certificate (ca.pem) so the server identity is verified.
    ssl = { ca: process.env.DATABASE_CA_CERT.replace(/\\n/g, '\n'), rejectUnauthorized: true };
  } else if (wantsSsl) {
    console.warn('[db] DATABASE_CA_CERT not set: connection is encrypted but the server certificate is not verified.');
    ssl = { rejectUnauthorized: false };
  }
  const pool = new pg.Pool({ connectionString: url.toString(), ssl, max: Number(process.env.DATABASE_POOL) || 10 });

  // `?` -> `$1, $2, ...` (our SQL never contains a literal question mark).
  const toPg = (sql) => {
    let i = 0;
    return sql.replace(/\?/g, () => `$${++i}`);
  };
  const api = (q) => ({
    all: async (sql, ...p) => (await q(toPg(sql), p)).rows,
    get: async (sql, ...p) => (await q(toPg(sql), p)).rows[0],
    run: async (sql, ...p) => ({ changes: (await q(toPg(sql), p)).rowCount }),
  });

  return {
    kind: 'postgres',
    ...api((sql, p) => pool.query(sql, p)),
    exec: (sql) => pool.query(sql),
    async tx(fn) {
      const client = await pool.connect();
      try {
        await client.query('BEGIN');
        const result = await fn(api((sql, p) => client.query(sql, p)));
        await client.query('COMMIT');
        return result;
      } catch (err) {
        await client.query('ROLLBACK').catch(() => {});
        throw err;
      } finally {
        client.release();
      }
    },
    close: () => pool.end(),
  };
}

// ---------------------------------------------------------------------------
// SQLite (built into Node 22.13+)
// ---------------------------------------------------------------------------
function createSqlite() {
  const { DatabaseSync } = require('node:sqlite');
  const file = new DatabaseSync(path.join(DATA_DIR, 'travia.db'));
  file.exec('PRAGMA journal_mode = WAL; PRAGMA foreign_keys = ON; PRAGMA busy_timeout = 5000;');
  const api = {
    all: async (sql, ...p) => file.prepare(sql).all(...p),
    get: async (sql, ...p) => file.prepare(sql).get(...p),
    run: async (sql, ...p) => ({ changes: Number(file.prepare(sql).run(...p).changes) }),
  };
  return {
    kind: 'sqlite',
    ...api,
    exec: async (sql) => file.exec(sql),
    // SQLite is synchronous underneath, so a transaction whose callback only awaits these
    // calls cannot interleave with other requests.
    async tx(fn) {
      file.exec('BEGIN');
      try {
        const result = await fn(api);
        file.exec('COMMIT');
        return result;
      } catch (err) {
        file.exec('ROLLBACK');
        throw err;
      }
    },
    close: async () => file.close(),
    raw: file,
  };
}

const db = IS_PG ? createPg() : createSqlite();

const DEFAULT_SETTINGS = {
  school_name: 'Travia Cafe',
  tagline: 'Practical cybersecurity training — self-paced, live online, or in person.',
  default_price_self: '1000',
  default_price_live: '1000',
  default_price_physical: '2500',
  mpesa_method: 'till', // till | paybill | phone
  mpesa_number: '',
  mpesa_account_name: '',
  contact_phone: '',
  contact_email: '',
  notify_email: '', // where "new payment to review" alerts go
};

/** Creates tables and default settings. Safe to run on every start. */
async function init() {
  if (db.kind === 'sqlite') {
    // Local databases created before student accounts existed.
    const tables = (await db.all("SELECT name FROM sqlite_master WHERE type = 'table'")).map((t) => t.name);
    if (tables.includes('enrollments')) {
      const cols = (await db.all('PRAGMA table_info(enrollments)')).map((c) => c.name);
      if (!cols.includes('student_id')) {
        await db.exec('ALTER TABLE enrollments ADD COLUMN student_id INTEGER REFERENCES students(id) ON DELETE SET NULL');
      }
    }
    await db.exec('DROP TABLE IF EXISTS viewer_access');
  }
  await db.exec(schema(db.kind === 'postgres'));
  for (const [k, v] of Object.entries(DEFAULT_SETTINGS)) {
    await db.run('INSERT INTO settings (key, value) VALUES (?, ?) ON CONFLICT (key) DO NOTHING', k, v);
  }
}

async function getSettings() {
  const out = {};
  for (const row of await db.all('SELECT key, value FROM settings')) out[row.key] = row.value;
  return out;
}

async function setSettings(values) {
  await db.tx(async (t) => {
    for (const [k, v] of Object.entries(values)) {
      await t.run('INSERT INTO settings (key, value) VALUES (?, ?) ON CONFLICT (key) DO UPDATE SET value = excluded.value', k, String(v));
    }
  });
}

module.exports = { db, init, DATA_DIR, VIDEO_DIR, DEFAULT_SETTINGS, getSettings, setSettings };
